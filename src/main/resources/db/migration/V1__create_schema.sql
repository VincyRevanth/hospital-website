CREATE TABLE specialty (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_specialty_name UNIQUE (name)
);

CREATE TABLE doctor (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug                VARCHAR(100) NOT NULL,
    full_name           VARCHAR(150) NOT NULL,
    qualification       VARCHAR(200) NOT NULL,
    bio                 VARCHAR(4000),
    registration_number VARCHAR(100),
    photo_path          VARCHAR(255),
    specialty_id        BIGINT REFERENCES specialty (id),
    display_order       INTEGER NOT NULL DEFAULT 0,
    active              BOOLEAN NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_doctor_slug UNIQUE (slug)
);
CREATE INDEX idx_doctor_active_order ON doctor (active, display_order);

CREATE TABLE service_offering (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(150) NOT NULL,
    description   VARCHAR(2000),
    display_order INTEGER NOT NULL DEFAULT 0,
    active        BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_service_offering_name UNIQUE (name)
);

CREATE TABLE admin_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(30) NOT NULL DEFAULT 'ROLE_ADMIN',
    enabled       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_admin_user_username UNIQUE (username)
);

CREATE TABLE contact_message (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    phone      VARCHAR(20),
    email      VARCHAR(150),
    message    VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_contact_message_created ON contact_message (created_at);

CREATE TABLE appointment (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_name   VARCHAR(100) NOT NULL,
    phone          VARCHAR(20) NOT NULL,
    email          VARCHAR(150),
    doctor_id      BIGINT REFERENCES doctor (id),
    service_id     BIGINT REFERENCES service_offering (id),
    preferred_date DATE NOT NULL,
    preferred_time TIME NOT NULL,
    message        VARCHAR(500),
    status         VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    version        BIGINT NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_appointment_status
        CHECK (status IN ('PENDING', 'CONFIRMED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_appointment_target
        CHECK (doctor_id IS NOT NULL OR service_id IS NOT NULL)
);
CREATE INDEX idx_appointment_date_status ON appointment (preferred_date, status);
CREATE INDEX idx_appointment_doctor_slot ON appointment (doctor_id, preferred_date, preferred_time);