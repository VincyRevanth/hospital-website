CREATE TABLE patient (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_code    VARCHAR(20),
    full_name       VARCHAR(100) NOT NULL,
    age_years       INTEGER NOT NULL,
    age_recorded_on DATE NOT NULL,
    gender          VARCHAR(10) NOT NULL,
    phone           VARCHAR(20) NOT NULL,
    address         VARCHAR(300),
    guardian_name   VARCHAR(100),
    created_by      VARCHAR(50) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_patient_code UNIQUE (patient_code),
    CONSTRAINT ck_patient_age CHECK (age_years BETWEEN 0 AND 120),
    CONSTRAINT ck_patient_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER'))
);
CREATE INDEX idx_patient_phone ON patient (phone);
CREATE INDEX idx_patient_name ON patient (full_name);

CREATE TABLE consultation (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id        BIGINT NOT NULL REFERENCES patient (id),
    doctor_id         BIGINT REFERENCES doctor (id),
    consultation_date DATE NOT NULL,
    valid_until       DATE NOT NULL,
    created_by        VARCHAR(50) NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_consultation_validity CHECK (valid_until >= consultation_date)
);
CREATE INDEX idx_consultation_patient_date ON consultation (patient_id, consultation_date);

ALTER TABLE hospital_settings ADD COLUMN consultation_validity_days INTEGER NOT NULL DEFAULT 15;
ALTER TABLE hospital_settings ADD CONSTRAINT ck_hospital_settings_validity
    CHECK (consultation_validity_days BETWEEN 1 AND 365);